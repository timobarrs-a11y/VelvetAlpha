// Add aliases to the map so old codes still resolve
for (const [alias, realCode] of Object.entries(ALIASES)) {
  const entry = SMILIE_MAP.get(realCode);
  if (entry) SMILIE_MAP.set(alias, { ...entry, code: alias });
}

export const SMILIE_REGEX = /:([a-z0-9]+):/gi;

export function smilieUrl(code: string): string | null {
  const entry = SMILIE_MAP.get(code.toLowerCase());
  return entry ? `${SMILIE_BASE}${entry.file}` : null;
}

